"""Writes mod/PalworldArchipelago/Scripts/area_centres.lua: for each area of area_labels.png (one area index per
pixel), the point deepest inside it (largest distance to its edge), and the point nearest the starting area that is
still a whole stamp inside it, both as 0-1 map coordinates. The map stamp for a locked area is drawn at the second
(v0.13.5 playtest: at the deepest point it sat under the map's fog of war, which a locked area never clears; the side
facing home is the side players walk up to), or the first when the area is too thin for a stamp.
    python tools/area_centres.py      (needs numpy, scipy, pillow)"""
from pathlib import Path

import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / 'mod' / 'PalworldArchipelago'
labels = np.array(Image.open(MOD / 'area_labels.png'))
n = labels.shape[0]
START = 1                                            # Windswept Island (area_walls.lua: areas, from 0 = Open sea)
INSET = 56 * n / 4096                                # walls.lua's 88 px stamp on the 4096 map: half of it, plus 12
from_start = distance_transform_edt(labels != START)
lines = ['-- Generated by tools/area_centres.py from area_labels.png; do not edit by hand.',
         '-- area index -> { u, v, nu, nv }: the point deepest inside the area, and the point nearest the starting area',
         '-- with a whole stamp inside it (the stamp goes there), 0-1 across and down the map.', 'return {']
for k in range(1, int(labels.max()) + 1):
    inside = np.pad(labels == k, 1)                  # padded so the image edge counts as an edge
    if not inside.any():
        continue
    depth = distance_transform_edt(inside)[1:-1, 1:-1]
    r, c = np.unravel_index(np.argmax(depth), depth.shape)
    room = depth >= INSET
    if room.any():
        near = np.where(room, from_start, np.inf)
        nr, nc = np.unravel_index(np.argmin(near), near.shape)
    else:
        nr, nc = r, c
    lines.append(f'    [{k}] = {{ {(c + 0.5) / n:.4f}, {(r + 0.5) / n:.4f}, {(nc + 0.5) / n:.4f}, {(nr + 0.5) / n:.4f} }},'
                 f'   -- {depth[r, c] * 1.0:.0f} px deep; {from_start[nr, nc]:.0f} px from the start')
lines.append('}')
(MOD / 'Scripts' / 'area_centres.lua').write_text('\n'.join(lines) + '\n')
print('\n'.join(lines))
