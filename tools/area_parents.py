"""Writes mod/PalworldArchipelago/Scripts/area_parents_regions.lua: each of the 75 regions (area_size regions) and the
area of the 15 it lies in, so a region can wear its area's wall colour, pass ticket and map stamp. A region belongs to
the area holding its first row (tools/area_groups.py); the regions were cut from the areas' rows.
    python3 tools/area_parents.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from area_groups import GROUPS, REGIONS  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), '..', 'mod', 'PalworldArchipelago', 'Scripts', 'area_parents_regions.lua')


def main():
    of_row = {row: area for area, rows in GROUPS.items() for row in rows}
    lines = ['-- Generated by tools/area_parents.py: each region (area_size regions) -> the area it lies in.', 'return {']
    missing = []
    for region, rows in REGIONS.items():
        area = next((of_row[r] for r in rows if r in of_row), None)
        if area is None:
            missing.append(region)
            continue
        assert '"' not in region + area and '\\' not in region + area, region
        lines.append(f'    ["{region}"] = "{area}",')
    lines.append('}')
    if missing:
        sys.exit(f'no area for: {", ".join(missing)}')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {OUT}: {len(REGIONS)} regions')


if __name__ == '__main__':
    main()
